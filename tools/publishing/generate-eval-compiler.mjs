import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { version as esbuildVersion, transform } from 'esbuild';

const require = createRequire(import.meta.url);
const sourcePath = require.resolve('typescript');
const version = require('typescript/package.json').version;
const source = await readFile(sourcePath, 'utf8');
const sha256 = createHash('sha256').update(source).digest('hex');
const outputUrl = new URL(
  '../../packages/runtime-js/src/module-loader/generated/typescript-browser.js',
  import.meta.url,
);
const expectedHash = '3ae902c92cc44dace175c0e69e13a4b0899f6983c6121d76b9ab8dd5795e7675';
if (version !== '5.9.3' || sha256 !== expectedHash || esbuildVersion !== '0.28.0') {
  throw new Error(
    `Compiler provenance changed: TypeScript ${version}/${sha256}, esbuild ${esbuildVersion}; re-probe ADR-0381 before updating pins`,
  );
}
const mode = process.argv[2];
if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) {
  throw new Error('Usage: node tools/publishing/generate-eval-compiler.mjs --write|--check');
}
// Unmodified upstream source in its original browser environment. No runtime
// evaluation or global mutation; the host's Node shims cannot select ts.sys.
const result = await transform(
  `const compiler = (() => {
const process = undefined;
const require = undefined;
const module = { exports: {} };
${source}
return module.exports;
})();
export default compiler;`,
  {
    format: 'esm',
    target: 'es2022',
    minify: true,
    legalComments: 'eof',
  },
);
const output = `// Generated by tools/publishing/generate-eval-compiler.mjs; do not edit.\n// TypeScript ${version}, sha256 ${sha256}; esbuild ${esbuildVersion}. ADR-0381.\n${result.code}`;
if (mode === '--write') {
  await mkdir(dirname(fileURLToPath(outputUrl)), { recursive: true });
  await writeFile(outputUrl, output);
} else if ((await readFile(outputUrl, 'utf8')) !== output) {
  throw new Error('Eval compiler drift: run pnpm eval-compiler:generate');
}
console.log(`eval-compiler ${mode}: TypeScript ${version}, ${Buffer.byteLength(output)} bytes`);
