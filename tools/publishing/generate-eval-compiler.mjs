import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { version as esbuildVersion, transform } from 'esbuild';
import { legalComment } from './legal-comment.mjs';

const require = createRequire(import.meta.url);
const sourcePath = require.resolve('typescript');
const version = require('typescript/package.json').version;
const source = await readFile(sourcePath, 'utf8');
const sha256 = createHash('sha256').update(source).digest('hex');
const outputUrl = new URL(
  '../../packages/runtime-js/src/module-loader/generated/typescript-browser.js',
  import.meta.url,
);
const expectedHash = '3ae902c92cc44dace175c0e69e13a4b0899f6983c6121d76b9ab8dd5795e7675';
if (version !== '5.9.3' || sha256 !== expectedHash || esbuildVersion !== '0.28.0') {
  throw new Error(
    `Compiler provenance changed: TypeScript ${version}/${sha256}, esbuild ${esbuildVersion}; re-probe ADR-0381 before updating pins`,
  );
}
const mode = process.argv[2];
if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) {
  throw new Error('Usage: node tools/publishing/generate-eval-compiler.mjs --write|--check');
}
// Unmodified upstream source in its original browser environment. No runtime
// evaluation or global mutation; the host's Node shims cannot select ts.sys.
const result = await transform(
  `const compiler = (() => {
const process = undefined;
const require = undefined;
const module = { exports: {} };
${source}
return module.exports;
})();
export default compiler;`,
  {
    format: 'esm',
    target: 'es2022',
    minify: true,
    legalComments: 'eof',
  },
);
// Apache-2.0 §4(a) license copy, §4(b) change notice; §4(c) Microsoft header stays (eof).
const tsRoot = join(dirname(sourcePath), '..');
const license = await readFile(join(tsRoot, 'LICENSE.txt'), 'utf8');
// Already a `/*! … */` legal comment; embedded verbatim.
const thirdParty = await readFile(join(tsRoot, 'ThirdPartyNoticeText.txt'), 'utf8');
const notice = legalComment(
  license,
  `TypeScript ${version} (Apache-2.0). Changed by rifty: lib/typescript.js wrapped in a browser-scoped module (process, require undefined) and minified by esbuild ${esbuildVersion} (tools/publishing/generate-eval-compiler.mjs, ADR-0381).`,
);
const output = `// Generated by tools/publishing/generate-eval-compiler.mjs; do not edit.\n// TypeScript ${version}, sha256 ${sha256}; esbuild ${esbuildVersion}. ADR-0381.\n${notice}${thirdParty.trimEnd()}\n${result.code}`;
const files = new Map([
  [outputUrl, output],
  [new URL('typescript.LICENSE', outputUrl), license],
  [new URL('typescript-third-party.LICENSE', outputUrl), thirdParty],
]);
if (mode === '--write') {
  await mkdir(dirname(fileURLToPath(outputUrl)), { recursive: true });
  for (const [url, bytes] of files) await writeFile(url, bytes);
} else if (
  (
    await Promise.all(
      [...files].map(async ([url, bytes]) => (await readFile(url, 'utf8')) === bytes),
    )
  ).includes(false)
) {
  throw new Error('Eval compiler drift: run pnpm eval-compiler:generate');
}
console.log(`eval-compiler ${mode}: TypeScript ${version}, ${Buffer.byteLength(output)} bytes`);
