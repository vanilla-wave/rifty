// Variant guest bundles with Node's TextDecoder/TextEncoder (probe only, not shipped).
//   node docs/backlog/epics/isolate-guest-web-api/reference/textdecoder/bundle/build.mjs
// After `pnpm --filter @riftydev/isolate-host build` (the base). Network: raw.githubusercontent.com
// (Node v24.16.0 lib/internal/encoding*.js, sha256-pinned) and the npm registry (`npm ci` of
// ../deps). Writes packages/isolate-host/node_modules/.web-api-probe/td-{full,gb}/dist (a copy of the
// host dist with guest.js replaced; gitignored) and sizes.json beside this file.
//   td-full  @exodus/bytes as published (all multi-byte tables in its JSON)
//   td-gb    the same, its multi-byte JSON trimmed to gb18030 (+ ranges, shared chunks)
//   td-none  Node's class + single-byte only, no utf-16/gb18030 engine (timing attribution)
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../../../../../..');
const guestPkg = join(root, 'packages/isolate-guest');
const hostPkg = join(root, 'packages/isolate-host');
const out = join(hostPkg, 'node_modules/.web-api-probe');
const { build } = createRequire(join(guestPkg, 'package.json'))('esbuild');

const NODE = 'https://raw.githubusercontent.com/nodejs/node/v24.16.0';
const PINS = {
  'internal/encoding': [
    'lib/internal/encoding.js',
    '569b962eccc86b00a2948e452a324f5db1c01a15ef8a9164ec11c1005819ed70',
  ],
  'internal/encoding/single-byte': [
    'lib/internal/encoding/single-byte.js',
    '0823a43fec61145a5f5f96d1e5ec532a1720d6ef7fe147361221ec232905859b',
  ],
  'internal/encoding/util': [
    'lib/internal/encoding/util.js',
    'd2b4b86ac88c150a3cd099419287381f3efffd5650de553ec0e2637eb98b9b07',
  ],
};
const cache = join(tmpdir(), 'rifty-textdecoder-bundle-probe');
mkdirSync(cache, { recursive: true });
const src = {};
for (const [id, [path, sha]] of Object.entries(PINS)) {
  const file = join(cache, path.replaceAll('/', '_'));
  if (!existsSync(file)) execFileSync('curl', ['-sSfL', '-o', file, `${NODE}/${path}`]);
  const got = createHash('sha256').update(readFileSync(file)).digest('hex');
  if (got !== sha) throw new Error(`${path}: sha256 ${got} != ${sha}`);
  src[id] = readFileSync(file, 'utf8');
}
const deps = join(cache, 'deps');
if (!existsSync(join(deps, 'node_modules'))) {
  cpSync(join(here, '../deps'), deps, { recursive: true });
  execFileSync('npm', ['ci', '--ignore-scripts', '--no-audit', '--no-fund'], {
    cwd: deps,
    stdio: 'ignore',
  });
}
const exodusDir = join(deps, 'node_modules/@exodus/bytes');
const exodusVersion = JSON.parse(readFileSync(join(exodusDir, 'package.json'), 'utf8')).version;

// 1. Node's three files, verbatim, as a tiny module registry.
const gen = (ids) =>
  `'use strict';\n// Generated by build.mjs from Node v24.16.0 sources (verbatim bodies).\nmodule.exports = function loadNode(primordials, internalBinding, map) {\n  const defs = {\n${ids
    .map(
      (id) =>
        `    ${JSON.stringify(id)}: function (module, exports, require) {\n${src[id]}\n    },`,
    )
    .join(
      '\n',
    )}\n  };\n  const cache = {};\n  function require(id) {\n    if (Object.hasOwn(map, id)) return map[id];\n    if (!Object.hasOwn(defs, id)) throw new Error('probe: require(' + id + ')');\n    if (cache[id]) return cache[id].exports;\n    const m = (cache[id] = { exports: {} });\n    defs[id](m, m.exports, require);\n    return m.exports;\n  }\n  return require;\n};\n`;
const work = join(out, 'td-work');
mkdirSync(work, { recursive: true });
const genFile = join(work, 'node-encoding.gen.cjs');
writeFileSync(genFile, gen(Object.keys(PINS)));

// 2. @exodus/bytes' TextDecoder, pure-JS path (no host Buffer; neutral platform).
const exodusPlugin = (trim) => ({
  name: 'exodus-pure',
  setup(b) {
    // Every read of the host's Buffer, so the pure-JS path runs (the guest's rifty Buffer is
    // not Node's: its base64 decoder refuses base64url input, see README).
    const NO_BUFFER = [
      [
        /fallback[\\/]platform\.native\.js$/,
        'const { Buffer } = globalThis',
        'const Buffer = undefined',
      ],
      [
        /[\\/]base64\.js$/,
        'const { Buffer, atob, btoa } = globalThis',
        'const Buffer = undefined; const { atob, btoa } = globalThis',
      ],
      [/[\\/]array\.js$/, 'const Buffer = globalThis.Buffer', 'const Buffer = undefined'],
      [
        /fallback[\\/]_utils\.js$/,
        'const Buffer = /* @__PURE__ */ (() => globalThis.Buffer)()',
        'const Buffer = undefined',
      ],
    ];
    for (const [filter, from, to] of NO_BUFFER)
      b.onLoad({ filter }, (args) => {
        const s = readFileSync(args.path, 'utf8');
        if (args.path.includes('/fallback/') !== filter.source.includes('fallback'))
          return undefined;
        if (!s.includes(from)) throw new Error(`anchor missing: exodus ${from}`);
        return { contents: s.replace(from, to), loader: 'js' };
      });
    if (trim)
      b.onLoad({ filter: /multi-byte\.encodings\.json$/ }, (args) => {
        const j = JSON.parse(readFileSync(args.path, 'utf8'));
        const kept = Object.fromEntries(
          Object.entries(j).filter(
            ([k]) => k.startsWith('$') || k === 'gb18030' || k === 'gb18030-ranges',
          ),
        );
        return { contents: JSON.stringify(kept), loader: 'json' };
      });
  },
});
const exodusFiles = {};
for (const [name, trim] of [
  ['full', false],
  ['gb', true],
]) {
  const file = join(work, `exodus-${name}.cjs`);
  await build({
    stdin: {
      contents: "export { TextDecoder } from '@exodus/bytes/encoding.js';",
      resolveDir: deps,
      loader: 'js',
    },
    bundle: true,
    platform: 'neutral',
    mainFields: ['module', 'main'],
    conditions: [],
    format: 'cjs',
    target: 'es2022',
    outfile: file,
    logLevel: 'warning',
    legalComments: 'none',
    plugins: [exodusPlugin(trim)],
  });
  exodusFiles[name] = file;
}

// 3. Guest variants.
const SHIM = /src\/guest\/web-shim\.ts$/;
const ANCHOR = "define('TextEncoder', TextEncoder);\ndefine('TextDecoder', TextDecoder);";
const guestBuild = (outfile, exodus, minify) =>
  build({
    absWorkingDir: guestPkg,
    entryPoints: ['src/guest/entry.ts'],
    inject: ['src/guest/web-shim.ts'],
    outfile,
    bundle: true,
    target: 'es2022',
    logLevel: 'warning',
    legalComments: 'none',
    platform: 'browser',
    format: 'iife',
    external: ['node:module'],
    minify,
    plugins: exodus
      ? [
          {
            name: 'node-encoding',
            setup(b) {
              b.onLoad({ filter: SHIM }, (args) => {
                const s = readFileSync(args.path, 'utf8');
                if (!s.includes(ANCHOR))
                  throw new Error('anchor missing: web-shim TextEncoder/TextDecoder');
                const repl = `import __makeNodeEncoding from ${JSON.stringify(join(here, 'shim.cjs'))};
import __loadNode from ${JSON.stringify(genFile)};
const __nodeEncoding = __makeNodeEncoding({
  GuestTextDecoder: TextDecoder,
  GuestTextEncoder: TextEncoder,
  encodeUtf8,
  notImplemented,
  loadNode: __loadNode,
  loadExodus: ${exodus === 'none' ? "() => { throw new Error('probe: no engine in td-none'); }" : `() => require(${JSON.stringify(exodus)})`},
});
define('TextEncoder', __nodeEncoding.TextEncoder);
define('TextDecoder', __nodeEncoding.TextDecoder);`;
                return { contents: s.replace(ANCHOR, repl), loader: 'ts' };
              });
            },
          },
        ]
      : [],
  });

const sizes = {};
const measure = (file) => {
  const b = readFileSync(file);
  return { bytes: b.length, gzip9: gzipSync(b, { level: 9 }).length };
};
const minDir = join(work, 'min');
mkdirSync(minDir, { recursive: true });
await guestBuild(join(minDir, 'base.min.js'), null, true);
sizes.base = {
  guest: measure(join(hostPkg, 'dist/guest.js')),
  minified: measure(join(minDir, 'base.min.js')),
};
for (const [name, exodus] of [...Object.entries(exodusFiles), ['none', 'none']]) {
  const dir = join(out, `td-${name}`, 'dist');
  rmSync(dir, { recursive: true, force: true });
  cpSync(join(hostPkg, 'dist'), dir, { recursive: true });
  await guestBuild(join(dir, 'guest.js'), exodus, false);
  await guestBuild(join(minDir, `td-${name}.min.js`), exodus, true);
  sizes[`td-${name}`] = {
    guest: measure(join(dir, 'guest.js')),
    minified: measure(join(minDir, `td-${name}.min.js`)),
  };
  console.log(`td-${name}: ${dir}/guest.js`);
}

// 4. Parts, each minified on its own (esbuild IIFE).
const part = async (name, contents, resolveDir, platform = 'browser') => {
  const file = join(minDir, `part-${name}.js`);
  await build({
    stdin: { contents, resolveDir, loader: 'js' },
    bundle: true,
    minify: true,
    platform,
    format: 'iife',
    target: 'es2022',
    outfile: file,
    logLevel: 'warning',
    legalComments: 'none',
  });
  sizes[`part:${name}`] = measure(file);
};
writeFileSync(join(work, 'gen-single-byte.cjs'), gen(['internal/encoding/single-byte']));
writeFileSync(join(work, 'gen-class.cjs'), gen(['internal/encoding', 'internal/encoding/util']));
await part(
  'node single-byte.js',
  `globalThis.x = require(${JSON.stringify(join(work, 'gen-single-byte.cjs'))});`,
  work,
);
await part(
  'node encoding.js + util.js + shim.cjs',
  `globalThis.x = [require(${JSON.stringify(join(work, 'gen-class.cjs'))}), require(${JSON.stringify(join(here, 'shim.cjs'))})];`,
  work,
);
for (const [name, exodus] of Object.entries(exodusFiles))
  await part(
    `@exodus/bytes ${exodusVersion} (${name})`,
    `globalThis.x = require(${JSON.stringify(exodus)});`,
    work,
  );
sizes.versions = {
  node: 'v24.16.0 sources',
  exodus: exodusVersion,
  esbuild: createRequire(join(guestPkg, 'package.json'))('esbuild/package.json').version,
};
writeFileSync(join(here, 'sizes.json'), `${JSON.stringify(sizes, null, 2)}\n`);
console.log(JSON.stringify(sizes, null, 2));
